from datetime import datetime, timezone
from io import BytesIO
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

def build_pdf_report(title: str, sections: list[dict]) -> bytes:
    output=BytesIO()
    pdf=canvas.Canvas(output,pagesize=A4)
    width,height=A4
    y=height-55
    pdf.setTitle(title[:200])
    pdf.setFont("Helvetica-Bold",16); pdf.drawString(48,y,title[:90]); y-=24
    pdf.setFont("Helvetica",8); pdf.drawString(48,y,"Generated by Data Analyzer API | "+datetime.now(timezone.utc).isoformat()); y-=28
    for section in sections:
        heading=str(section.get("heading","Section"))[:100]
        body=str(section.get("body",""))
        pdf.setFont("Helvetica-Bold",11); pdf.drawString(48,y,heading); y-=17
        pdf.setFont("Helvetica",9)
        for line in body.splitlines() or [""]:
            while line:
                chunk,line=line[:105],line[105:]
                if y<55: pdf.showPage(); y=height-55; pdf.setFont("Helvetica",9)
                pdf.drawString(48,y,chunk); y-=13
        y-=12
        if y<70: pdf.showPage(); y=height-55
    pdf.save()
    return output.getvalue()
